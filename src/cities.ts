/** Case- and diacritic-insensitive ("malmo" finds Malmö). */
function fold(s: string): string {
  return s
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "")
    .toLowerCase();
}

/**
 * Prefix matches rank before substring matches; needs ≥2 characters so a
 * single keystroke doesn't dump half the list.
 */
export function searchCities(query: string, limit = 8): City[] {
  const q = fold(query.trim());
  if (q.length < 2) return [];
  const starts: City[] = [];
  const contains: City[] = [];
  for (const [name, country, lat, lng] of CITY_DATA) {
    const folded = fold(name);
    if (folded.startsWith(q)) {
      starts.push({ name, country, lat, lng });
      if (starts.length >= limit) break;
    } else if (contains.length < limit && folded.includes(q)) {
      contains.push({ name, country, lat, lng });
    }
  }
  return [...starts, ...contains].slice(0, limit);
}
